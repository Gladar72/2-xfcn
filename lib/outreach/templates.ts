export function firstMessageText(c: OutreachTemplateInput): string {
  if (c.platform === "ig") return c.kind === "blogger" ? bloggerTextShort(c) : publicTextShort(c);
  return c.kind === "blogger" ? bloggerText(c) : publicText(c);
}

export function reminderText(c: OutreachTemplateInput): string {
  if (c.kind === "blogger") {
    return "Привет! Напомню про «Место» — встреча с подписчиками, бесплатный «Премиум» и 30% с каждого, кто придёт по твоей ссылке. Если неинтересно — просто скажи, не буду отвлекать 🙂";
  }
  return `Здравствуйте! Напомню про предложение для «${c.name}» — подарок вашим подписчикам от тюменского сервиса «Место» и 30% вам с каждого приведённого человека по реферальной программе. Если неудобно — скажите, не буду отвлекать 🙂`;
}

