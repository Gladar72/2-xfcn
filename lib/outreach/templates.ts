/**
 * Тексты первого письма и напоминания для помощника по охвату.
 * Пишутся от имени Андрея (владельца «Места») — он отправляет их сам.
 */

export interface OutreachTemplateInput {
  name: string;
  kind: "public" | "blogger";
  greeting: string | null;
  acts: string | null;
  org_line: string | null;
  /** Instagram режет сообщения длиннее 1000 символов — для него короткие версии. */
  platform?: "tg" | "ig" | "vk";
}

const INTRO_PROJECTS =
  "Меня зовут Андрей, я занимаюсь открытием проектов в сфере HoReCa. В Тюмени есть и были наши проекты " +
  "«Ходят слухи», «150 метров», «Нити», «96 азиаток», а сейчас — FORMA LOUNGE.";

function publicText(c: OutreachTemplateInput): string {
  const greeting = c.greeting ?? "Здравствуйте!";
  const acts = c.acts ?? "кино, кофе, пробежка, вечеринка";
  const org =
    c.org_line ??
    "А предпринимателям «Место» помогает привлекать аудиторию: можно создать своё событие в городе — мастер-класс, ивент, концерт.";
  return [
    `${greeting} ${INTRO_PROJECTS}`,
    `Мы запустили свой первый сервис «Место» — мини-приложение в Telegram для тех, кому есть куда сходить, но не с кем: ${acts} — находишь встречу рядом и идёшь в компании. На карте города можно выбрать событие или создать своё. Особенно сервис выручает одиночек.`,
    org,
    `Хочу сделать подарок подписчикам «${c.name}»: месяц подписки «Старт» бесплатно по вашей ссылке. Для вас это полезный пост для аудитории, для нас — знакомство с городом.`,
    "А ещё у нас есть реферальная программа: вы получаете свою ссылку и 30% с каждого приведённого человека — со всех его оплат, без ограничения по времени. Так что для вас это не разовый пост, а постоянный доход.",
    "Готовы и к оплате, и к бартеру — как вам удобнее. Можно прислать текст и картинку? Если у вас только платное размещение — подскажите прайс.",
  ].join("\n\n");
}

