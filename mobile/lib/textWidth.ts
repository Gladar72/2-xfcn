/** tracking — межбуквенный интервал в долях кегля (заголовки — −0.03). */
export function textWidth(text: string, size: number, tracking = -0.03): number {
  let w = 0;
  for (const c of text) w += ADV.get(c) ?? 620;
  return (w / 1000) * size + size * tracking * Math.max(0, [...text].length - 1);
}

